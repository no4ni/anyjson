# 3) ищем родственные файлы той же линии
import re
pat = re.compile(r"[0-9a-f]{16,}")
print("\n=== РОДСТВЕННЫЕ ФАЙЛЫ (хеш в имени или 'approved') ===")
for f in sorted(os.listdir(src)):
    p = os.path.join(src, f)
    if not os.path.isfile(p): continue
    if "approved" in f.lower() or pat.search(f):
        print(f"  {f}   {os.path.getsize(p)} байт")
